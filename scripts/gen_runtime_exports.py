#!/usr/bin/env python3
"""Generates src/xex/rexglue_runtime_exports.inc: which Xbox 360 kernel/XAM exports the pinned
ReXGlue SDK runtime provides, read from the SDK sources (src/kernel/**):

    REX_EXPORT(__imp__Name, fn)            a real implementation (also the XBOXKRNL_/XAM_EXPORT aliases)
    REX_HOOK_RAW(__imp__Name) { ... }      a raw hook with direct context access (DbgPrint, the CRT printf family)
    REX_EXPORT_STUB(__imp__Name)           a stub: logs "<name> STUB" at warn level and returns
    REX_EXPORT_STUB_RETURN(__imp__Name, v) a stub that returns a fixed value
    SetVariableMapping("module", ordinal)  a variable export mapped into guest memory

Everything else the export tables know is "missing": generated code that calls such a function does
not link, and a variable import reads a garbage marker. A name that is both hooked and stubbed counts
as implemented. These are facts about the SDK's API surface (BSD-3-Clause); no code is copied.

    python3 -I scripts/gen_runtime_exports.py [--sdk third_party/rexglue-sdk/src] [--out src/xex/rexglue_runtime_exports.inc]

Re-run after bumping the SDK pin; the output is committed so the tools build without the checkout.
"""
import argparse
import os
import re
import sys

RE_IMPL = re.compile(r"\b(?:(?:REX|XBOXKRNL|XAM|XBDM)_EXPORT|REX_HOOK_RAW)\(\s*__imp__(\w+)")
RE_STUB = re.compile(r"\b(?:REX|XBOXKRNL|XAM|XBDM)_EXPORT_STUB(?:_RETURN)?\(\s*__imp__(\w+)")
RE_VAR = re.compile(r"SetVariableMapping\(\s*\"([^\"]+)\"\s*,\s*(0x[0-9A-Fa-f]+|\d+)")


def scan(kernel_dir):
    implemented, stubs, variables = set(), set(), set()
    for dirpath, _, files in os.walk(kernel_dir):
        for name in files:
            if not name.endswith((".cpp", ".cc", ".h", ".hpp", ".inc")):
                continue
            with open(os.path.join(dirpath, name), encoding="utf-8", errors="replace") as f:
                text = f.read()
            implemented.update(RE_IMPL.findall(text))
            stubs.update(RE_STUB.findall(text))
            for library, ordinal in RE_VAR.findall(text):
                variables.add((library.lower(), int(ordinal, 0)))
    stubs -= implemented
    return sorted(implemented), sorted(stubs), sorted(variables)


def read_pin(path):
    """The commit from third_party/rexglue-sdk/PIN (`commit=<sha>` lines; a bare sha also works)."""
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("commit="):
                    return line.split("=", 1)[1].strip()
                if line and not line.startswith("#") and "=" not in line:
                    return line.split()[0]
    except OSError:
        pass
    return "unknown"


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sdk", default=os.path.join(root, "third_party", "rexglue-sdk", "src"))
    ap.add_argument("--pin", default=os.path.join(root, "third_party", "rexglue-sdk", "PIN"))
    ap.add_argument("--out", default=os.path.join(root, "src", "xex", "rexglue_runtime_exports.inc"))
    args = ap.parse_args(argv[1:])
    kernel_dir = os.path.join(args.sdk, "src", "kernel")
    if not os.path.isdir(kernel_dir):
        print(f"missing {kernel_dir} (run scripts/fetch-rexglue-sdk.sh)", file=sys.stderr)
        return 2
    implemented, stubs, variables = scan(kernel_dir)
    if not implemented or not stubs:
        print("no exports found: the SDK layout changed, update this script", file=sys.stderr)
        return 2
    pin = read_pin(args.pin)
    out = [
        "// Generated by scripts/gen_runtime_exports.py from the pinned ReXGlue SDK checkout (BSD-3-Clause),",
        f"// commit {pin}. Do not edit; re-run the script instead.",
        "// Which kernel/XAM exports the SDK runtime provides: real implementations (REX_EXPORT, REX_HOOK_RAW), logging",
        "// stubs (REX_EXPORT_STUB*), and the variable exports it maps into guest memory. Names are sorted",
        "// bytewise for binary search; variables by (library, ordinal).",
        "// clang-format off",
        f'inline constexpr std::string_view kRuntimeExportsSdkCommit = "{pin}";',
        "inline constexpr const char* kRuntimeImplementedExports[] = {",
    ]
    out += [f'    "{n}",' for n in implemented]
    out += ["};", "inline constexpr const char* kRuntimeStubExports[] = {"]
    out += [f'    "{n}",' for n in stubs]
    out += ["};", "inline constexpr RuntimeVariableExport kRuntimeVariableExports[] = {"]
    out += [f'    {{"{lib}", 0x{ordinal:04X}}},' for lib, ordinal in variables]
    out += ["};", "// clang-format on"]
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(implemented)} implemented, {len(stubs)} stubs, {len(variables)} variables from {kernel_dir} -> {os.path.relpath(args.out, root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
