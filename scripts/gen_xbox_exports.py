#!/usr/bin/env python3
"""Generates src/xex/xbox_exports_table.inc: ordinal -> name tables of the Xbox 360 kernel and
XAM exports, from the tables in the pinned XenonRecomp checkout (XenonUtils/xbox/*.inc, which
XenonRecomp (MIT) took from Xenia (BSD-3-Clause)). These are facts about Microsoft's public
export ordinals, used to name the imports a game's XEX declares (`ttt2-xexinfo --imports`).

    python3 -I scripts/gen_xbox_exports.py [--xenonrecomp third_party/xenonrecomp/src] [--out src/xex/xbox_exports_table.inc]

Re-run after bumping the XenonRecomp pin; the output is committed so the tools build without
the checkout.
"""
import argparse
import os
import re
import sys

RE_EXPORT = re.compile(r"XE_EXPORT\(\s*(\w+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(\w+)\s*,\s*(kFunction|kVariable)\s*\)")


def read_table(path):
    entries = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for m in RE_EXPORT.finditer(f.read()):
            ordinal = int(m.group(2), 0)
            entries[ordinal] = (m.group(3), m.group(4) == "kVariable")
    return sorted(entries.items())


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--xenonrecomp", default=os.path.join(root, "third_party", "xenonrecomp", "src"))
    ap.add_argument("--out", default=os.path.join(root, "src", "xex", "xbox_exports_table.inc"))
    args = ap.parse_args(argv[1:])
    tables = {
        "kXboxkrnlExports": os.path.join(args.xenonrecomp, "XenonUtils", "xbox", "xboxkrnl_table.inc"),
        "kXamExports": os.path.join(args.xenonrecomp, "XenonUtils", "xbox", "xam_table.inc"),
    }
    out = ["// Generated by scripts/gen_xbox_exports.py from the XenonRecomp checkout (XenonUtils/xbox/*.inc,",
           "// MIT; the tables originate from Xenia, BSD-3-Clause). Do not edit; re-run the script instead.",
           "// Ordinal -> export name of the Xbox 360 kernel (xboxkrnl.exe) and XAM (xam.xex), sorted by",
           "// ordinal. `variable` marks data exports (the game imports their address, not a function).",
           "// clang-format off"]
    for name, path in tables.items():
        if not os.path.isfile(path):
            print(f"missing {path} (run scripts/fetch-xenonrecomp.sh)", file=sys.stderr)
            return 2
        entries = read_table(path)
        out.append(f"inline constexpr XboxExport {name}[] = {{")
        for ordinal, (sym, variable) in entries:
            out.append(f'    {{{ordinal}, "{sym}", {"true" if variable else "false"}}},')
        out.append("};")
        print(f"{name}: {len(entries)} exports from {os.path.relpath(path, root)}")
    out.append("// clang-format on")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
