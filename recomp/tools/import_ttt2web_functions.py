#!/usr/bin/env python3
"""Converts TTT2 Web's explicit function boundaries into ReXGlue's [functions] config.

TTT2 Web (monty488/tekkenwebtournament2, CC0 1.0 public domain) ships, in recomp/config/TTT2.toml,
a block generated by its tools/find_switch_tables.py on its author's executable:

    # BEGIN GENERATED FUNCTIONS (tools/find_switch_tables.py)
    functions = [
        { address = 0x82240088, size = 0x8 },
        ...
    ]
    # END GENERATED FUNCTIONS

Those are leaf functions without .pdata entries and .pdata functions whose reachable code outgrows
the recorded size (jump tables, bdzf chains): exactly the boundaries a recompiler guesses wrong.
ReXGlue takes the same facts as a [functions] table keyed by address:

    [functions]
    "0x82240088" = { size = 0x8 }

The addresses are only valid for an executable with the same layout as TTT2 Web's author's copy.
The eight register save/restore helper addresses published next to them are the fingerprint:
`ttt2-xexinfo --helpers` / `ttt2-validate` report whether a given image matches, and only then is the
converted file worth including (recomp/ttt2_manifest.ttt2web.toml does; the default manifest does
not). Addresses and sizes only; no game bytes are involved.

    python3 -I recomp/tools/import_ttt2web_functions.py <TTT2.toml> --out recomp/ttt2_functions.ttt2web.toml
"""
import argparse
import re
import sys

RE_ENTRY = re.compile(r"\{\s*address\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*size\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*\}")
RE_HELPER = re.compile(r"^(restgprlr_14|savegprlr_14|restfpr_14|savefpr_14|restvmx_14|savevmx_14|restvmx_64|savevmx_64)_address\s*=\s*(0x[0-9A-Fa-f]+)", re.M)


def parse(text):
    begin = text.find("# BEGIN GENERATED FUNCTIONS")
    end = text.find("# END GENERATED FUNCTIONS")
    block = text[begin:end] if begin >= 0 and end > begin else text
    entries = {}
    for m in RE_ENTRY.finditer(block):
        address, size = int(m.group(1), 16), int(m.group(2), 0)
        if size == 0:
            continue
        entries[address] = max(size, entries.get(address, 0))
    helpers = {name: int(value, 16) for name, value in RE_HELPER.findall(text)}
    return entries, helpers


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="TTT2 Web's recomp/config/TTT2.toml")
    ap.add_argument("--out", required=True, help="ReXGlue config file to write")
    args = ap.parse_args(argv[1:])
    with open(args.source, encoding="utf-8", errors="replace") as f:
        entries, helpers = parse(f.read())
    if not entries:
        print("no function entries found", file=sys.stderr)
        return 2
    lines = [
        "# Explicit function boundaries for Tekken Tag Tournament 2, converted by",
        "# recomp/tools/import_ttt2web_functions.py from TTT2 Web (monty488/tekkenwebtournament2, CC0 1.0),",
        "# recomp/config/TTT2.toml, block generated there by tools/find_switch_tables.py on its author's",
        "# executable. Addresses and sizes only.",
        "#",
        "# ONLY VALID FOR AN IMAGE WITH THE SAME LAYOUT AS TTT2 WEB'S: its published save/restore helper",
        "# addresses are the fingerprint (ttt2-xexinfo --helpers reports the match). Included by",
        "# recomp/ttt2_manifest.ttt2web.toml, never by the default manifest.",
        "# Helper addresses published alongside:",
    ]
    for name in sorted(helpers):
        lines.append(f"#   {name}: 0x{helpers[name]:08X}")
    lines.append("")
    lines.append("[functions]")
    for address in sorted(entries):
        lines.append(f'"0x{address:08X}" = {{ size = 0x{entries[address]:X} }}')
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(entries)} functions, {len(helpers)} helper addresses -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
