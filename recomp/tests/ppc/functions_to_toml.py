#!/usr/bin/env python3
"""Turns a test program's boundary list (`start_label end_label` per line, e.g. tailcall_ttt2.functions)
into a ReXGlue [functions] table, using the packer's symbol map (<image>.xex.syms) for the addresses:
the reference recomp/tools/resolve_functions.py checks a test program's codegen and boot errors
against, the way recomp/ttt2_functions.ttt2web.toml serves for the game. Test data only.

    python3 -I recomp/tests/ppc/functions_to_toml.py <image.xex.syms> <program.functions> <out.toml>
"""
import sys


def main(argv):
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    syms = {}
    with open(argv[1], encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if len(parts) == 4:
                syms[parts[3]] = int(parts[0], 16)
    out = ["# Boundary reference generated by recomp/tests/ppc/functions_to_toml.py (test data)", "[functions]"]
    with open(argv[2], encoding="utf-8") as f:
        for line in f:
            pair = line.split("#", 1)[0].split()
            if len(pair) != 2:
                continue
            start, end = syms[pair[0]], syms[pair[1]]
            if end <= start:
                print(f"bad pair {pair}: end before start", file=sys.stderr)
                return 1
            out.append(f'"0x{start:08X}" = {{ size = 0x{end - start:X} }}')
    with open(argv[3], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
